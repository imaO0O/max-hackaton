/**
 * Свободный текст в чате: частые темы узнаются по ключевым словам и ведут в нужный раздел.
 * Без ИИ и внешних сервисов — ответ предсказуем, текст сообщения никуда не передаётся
 * и не сохраняется (в метрики пишется только тема).
 */

/**
 * Порядок важен: «когда отбор в 10 класс» — про даты плана, «10 класс или колледж» — сравнение путей,
 * «напоминания подростку» — про напоминания, «отправить план сыну» — отправка плана,
 * «2 или 4 ОГЭ» — подсказка по числу экзаменов, «когда ОГЭ» — даты плана.
 */
const TOPICS = [
  ['help', /помощ|помоги|что (ты )?умеешь|какие команды|^команды/],
  ['delete', /удали|удалит/],
  ['reminders', /напомина|уведомлен/],
  ['share', /поделит|пересл|отправ\S* (план|ссылк)|подростку|сыну|дочер|дочк|ребенку/],
  // «2 или 4 огэ», «два экзамена», «сколько огэ сдавать» — до темы плана, где тоже есть «огэ»
  ['oge', /(^|[^0-9])[24]\s*(огэ|экзамен)|(два|двух|четыре|четырех)\s*(огэ|экзамен|предмет)|сколько\s*(огэ|экзамен)|эксперимент/],
  ['plan', /план|дат[аыу]|сроки|когда|огэ|экзамен|собеседован|заявлени|дедлайн|календар/],
  ['paths', /(^|[^0-9])10(-?й)?\s*кл|десят|сравн|что выбрать|какой путь|куда (пойти|идти|поступать)|остаться в школе/],
  ['colleges', /колледж|техникум|училищ|специальност|професси|проходн|бюджетн|общежит/],
  ['grades', /балл|оценк|аттестат|калькулятор|средн/],
  ['thanks', /спасиб|благодар/],
  ['greeting', /^(привет|здравств|добр(ый|ое|ого)|доброго|хай|hello|hi)/],
];

export const FREE_TEXT_TOPICS = TOPICS.map(([topic]) => topic);

/** Тема сообщения или null, если бот её не узнал. Неизвестная команда вида /что-то — справка. */
export function detectTopic(text) {
  const normalized = (text ?? '').trim().toLowerCase().replaceAll('ё', 'е');
  if (!normalized) return null;
  if (normalized.startsWith('/')) return 'help';
  return TOPICS.find(([, pattern]) => pattern.test(normalized))?.[0] ?? null;
}
